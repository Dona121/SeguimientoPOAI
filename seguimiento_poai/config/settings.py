def _static_versionado(ruta):
    """Cuelga ?v=<mtime> a un estatico para reventar la cache del navegador.

    Sin esto, cada cambio en el CSS obliga a un Ctrl+F5 en cada maquina del
    equipo: el navegador reusa la version vieja. Al ligar la version a la fecha
    de modificacion del archivo, cada edicion cambia la URL y se vuelve a bajar.
    """
    archivo = BASE_DIR / "static" / ruta
    version = int(archivo.stat().st_mtime) if archivo.exists() else 0
    return lambda request: f"{static(ruta)}?v={version}"


